defmodule KeyfleetWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :keyfleet

  # A connected mount reads the cookie the socket handshake carried, so the
  # transport must decode it with the same options the request plug runs with.
  @session_options {Application, :fetch_env!, [:keyfleet, :session_options]}

  # A stylesheet, an icon or an image may be opened directly, and the browser
  # then reads it as a page. These say what a page from this address may do,
  # which is nothing.
  @static_headers %{
    "content-security-policy" => "default-src 'none'; frame-ancestors 'none'",
    "x-content-type-options" => "nosniff",
    "x-frame-options" => "DENY",
    "referrer-policy" => "no-referrer"
  }

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [:peer_data, :uri, session: @session_options]],
    longpoll: [connect_info: [:peer_data, :uri, session: @session_options]]

  plug KeyfleetWeb.Plugs.CanonicalHost
  plug KeyfleetWeb.Plugs.ContractHeaders

  # While the site is closed, only the early-access page, the legal pages, the
  # operational files and the static files get past this.
  plug KeyfleetWeb.Plugs.LaunchGate

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :keyfleet,
    gzip: not code_reloading?,
    only: KeyfleetWeb.static_paths(),
    only_matching: KeyfleetWeb.digested_static_prefixes(),
    raise_on_missing_only: code_reloading?,
    headers: @static_headers

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
  end

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  # Every answer, including the Markdown and refusals the plugs below give
  # before the router, lets browser agents use the tools this site's pages
  # register, and no other site's.
  plug :allow_page_tools

  # One budget per client address, shared by the health check and every /api
  # path, answered or not. Every answer, including a signed agent request
  # refused before the router, says what is left of it; past it the answer is
  # 429 with Retry-After.
  plug :limit_rate

  plug KeyfleetWeb.Plugs.SignedAgent

  # Before the parsers, so a body they reject on an /api path is answered in
  # JSON like every other API error.
  plug RegentAgentAccess.Plug,
    documents: &KeyfleetWeb.PublicDocuments.document/1,
    guide: "/llms.txt"

  # The largest body the site takes is an agent's signed post or workspace
  # write, about 50 kilobytes, which SignedAgent reads under its own limit;
  # anything past a megabyte is refused before it is read.
  plug KeyfleetWeb.Plugs.Parsers,
    body_reader: {KeyfleetWeb.BodyReader, :read_body, []},
    parsers: [:urlencoded, :json],
    pass: ["*/*"],
    length: 1_000_000,
    json_decoder: Phoenix.json_library()

  plug Plug.Head
  plug KeyfleetWeb.Plugs.RuntimeSession

  plug KeyfleetWeb.Router

  defp limit_rate(%Plug.Conn{path_info: ["healthz"]} = conn, _opts),
    do: RegentAgentAccess.RateLimit.call(conn, rate_limit())

  defp limit_rate(%Plug.Conn{path_info: ["api" | _]} = conn, _opts),
    do: RegentAgentAccess.RateLimit.call(conn, rate_limit())

  defp limit_rate(conn, _opts), do: conn

  # Read on each request, as the session budget is, so the test suite can run
  # on a larger one and a focused test can put the release budget back.
  defp rate_limit do
    budget = Application.fetch_env!(:keyfleet, :api_rate_limit)

    RegentAgentAccess.RateLimit.init(
      policy: "default",
      limit: Keyword.fetch!(budget, :limit),
      window: Keyword.fetch!(budget, :window_seconds),
      admit: &Keyfleet.Accounts.RequestRateLimiter.admit/3,
      key: &KeyfleetWeb.ClientAddress.key/1
    )
  end

  defp allow_page_tools(conn, _opts),
    do: Plug.Conn.put_resp_header(conn, "permissions-policy", "tools=(self)")
end
